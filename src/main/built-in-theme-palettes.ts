/** The palette files first, then each built-in palette that no file replaces. */
export function withBuiltInThemePalettes(files: readonly AppThemePalette[]): AppThemePalette[] {
  const fileIds = new Set(files.map((palette) => palette.id));
  return [...files, ...BUILT_IN_THEME_PALETTES.filter((palette) => !fileIds.has(palette.id))];
}
